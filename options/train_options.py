from .base_options import BaseOptions


class TrainOptions(BaseOptions):
    def initialize(self):
        BaseOptions.initialize(self)
        p = self.parser
        p.add_argument('--display_freq', type=int, default=100)
        p.add_argument('--niter', type=int, default=300)
        p.add_argument('--learning_rate_decrease_itr', type=int, default=-1)
        p.add_argument('--decay_factor', type=float, default=0.94)
        p.add_argument('--validation_on', action='store_true')
        p.add_argument('--validation_freq', type=int, default=400)
        p.add_argument('--val_max_batches', type=int, default=0)
        p.add_argument('--val_split_n', type=int, default=0)
        p.add_argument('--epoch_save_freq', type=int, default=10)
        p.add_argument('--resume_dir', type=str)
        p.add_argument('--last_epoch', default=None, type=int)
        p.add_argument('--freeze_nets', action='store_true')
        p.add_argument('--teacher_cache_path', type=str, default='')
        p.add_argument('--validation_cache_path', type=str, default='')
        p.add_argument('--material_cache_path', type=str, default='')
        p.add_argument('--validation_material_cache_path', type=str, default='')
        p.add_argument('--mat_nclass', type=int, default=23)
        p.add_argument('--accumulation_steps', type=int, default=1)
        p.add_argument('--seed', type=int, default=0)
        p.add_argument('--deterministic', action='store_true')
        p.add_argument('--cosine_T_max', type=int, default=0)
        p.add_argument('--warmup_steps', type=int, default=0)
        p.add_argument('--ema_decay', type=float, default=0.0)
        p.add_argument('--early_stop_patience', type=int, default=0)
        p.add_argument('--depth_loss_type', type=str, default='log', choices=['log', 'silog', 'l1', 'l2', 'berhu'])
        p.add_argument('--lambda_teacher_depth', type=float, default=0.5)
        p.add_argument('--lambda_depth', type=float, default=1.0)
        p.add_argument('--lambda_mat', type=float, default=0.7)
        p.add_argument('--lambda_ccl_depth', type=float, default=0.3)
        p.add_argument('--lambda_ccl_mat', type=float, default=0.0)
        p.add_argument('--lambda_ct', type=float, default=0.05)
        p.add_argument('--ct_am_scale', type=float, default=1.0)
        p.add_argument('--lambda_multiscale', type=float, default=0.0)
        p.add_argument('--lambda_laplacian', type=float, default=0.0)
        p.add_argument('--lambda_ssim', type=float, default=0.0)
        p.add_argument('--lambda_grad', type=float, default=0.0)
        p.add_argument('--lambda_feat_std', type=float, default=0.0)
        p.add_argument('--feat_std_gamma', type=float, default=0.5)
        p.add_argument('--audio_decoder_dropout', type=float, default=-1.0)
        p.add_argument('--audio_norm_type', type=str, default='batchnorm', choices=['batchnorm', 'groupnorm', 'layernorm', 'instancenorm'])
        p.add_argument('--audio_norm_groups', type=int, default=8)
        p.add_argument('--ccl_temperature', type=float, default=1.0)
        p.add_argument('--ct_ad_loss', type=str, default='cosine', choices=['cosine', 'infonce'])
        p.add_argument('--ct_temperature', type=float, default=0.1)
        p.add_argument('--lambda_ldc', type=float, default=0.0)
        p.add_argument('--ldc_tau', type=float, default=0.1)
        p.add_argument('--ldc_grid', type=int, default=8)
        p.add_argument('--lambda_cc', type=float, default=0.0)
        p.add_argument('--cc_tau', type=float, default=0.1)
        p.add_argument('--teacher_depth_align', action='store_true')
        p.add_argument('--cache_freeze_teacher_proj', action='store_true')
        p.add_argument('--berhu_threshold', type=float, default=0.2)
        p.add_argument('--ccl_depth_loss', type=str, default='log', choices=['log', 'berhu'])
        p.add_argument('--berhu_teacher', action='store_true')
        p.add_argument('--use_se_skips', action='store_true')
        p.add_argument('--decoder_spatial_entry', action='store_true')
        p.add_argument('--use_film_ce', action='store_true')
        p.add_argument('--use_ln_proj', action='store_true')
        p.add_argument('--use_log_depth', action='store_true')
        p.add_argument('--use_silu', action='store_true')
        p.add_argument('--use_residual_decoder', action='store_true')
        p.add_argument('--wider_decoder', action='store_true')
        p.add_argument('--backbone', type=str, default='Resnet18', choices=['Resnet18', 'Resnet34', 'Legacy', 'MALFNet', 'DPT', 'DPT_BAST'])
        p.add_argument('--init_audiodepth_weight', type=str, default='')
        p.add_argument('--init_material_weight', type=str, default='')
        p.add_argument('--lr_backbone_main', type=float, default=0.0001)
        p.add_argument('--lr_audio', type=float, default=0.0001)
        p.add_argument('--optimizer', default='adam', type=str)
        p.add_argument('--beta1', default=0.9, type=float)
        p.add_argument('--weight_decay', default=0.0005, type=float)
        self.mode = 'train'
        self.isTrain = True
        self.enable_data_augmentation = True
